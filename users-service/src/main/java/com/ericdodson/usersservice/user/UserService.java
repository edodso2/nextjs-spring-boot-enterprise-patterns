package com.ericdodson.usersservice.user;

import org.springframework.dao.DuplicateKeyException;
import org.springframework.data.relational.core.conversion.DbActionExecutionException;
import org.springframework.http.HttpStatus;
import org.springframework.stereotype.Service;
import org.springframework.web.server.ResponseStatusException;

import java.util.List;

@Service
public class UserService {

    private final UserRepository userRepository;

    public UserService(UserRepository userRepository) {
        this.userRepository = userRepository;
    }

    public User createUser(User user) {
        // Ids are generated by the database; a client-supplied id would turn the insert into an update
        user.setId(null);
        try {
            return userRepository.save(user);
        } catch (DbActionExecutionException e) {
            // The unique constraint on email is the source of truth, so concurrent signups can't both succeed.
            // Spring Data JDBC wraps the translated DuplicateKeyException, so check the cause.
            if (e.getCause() instanceof DuplicateKeyException) {
                throw new ResponseStatusException(HttpStatus.CONFLICT, "Email already exists");
            }
            throw e;
        }
    }

    public List<User> getUsers() {
        return userRepository.findAll();
    }

    public User getUserById(Long id) {
        return userRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "User not found with id: " + id));
    }
}
